/**
 * Tek kaynaklı SVG ikon seti.
 *
 * Daha önce site genelinde ✓ ★ ♥ ↗ 👁 📄 gibi Unicode karakterleri ikon
 * olarak kullanılıyordu. Windows/Chrome bu karakterleri Segoe UI Symbol ve
 * Segoe UI Emoji'den bitmap olarak çizdiği için büyütüldüklerinde tırtıklı
 * görünüyorlardı. Buradaki ikonlar vektör olduğu için her ölçekte net.
 *
 * Hepsi currentColor kullanır — renk, kapsayıcıdaki text-* sınıfından gelir.
 */

interface IconProps {
  size?: number;
  className?: string;
  strokeWidth?: number;
}

function Svg({
  size = 16,
  className,
  strokeWidth = 2,
  children,
}: IconProps & { children: React.ReactNode }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      aria-hidden
      focusable="false"
    >
      {children}
    </svg>
  );
}

